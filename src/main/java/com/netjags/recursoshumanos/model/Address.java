package main.java.com.netjags.recursoshumanos.model;

/**
 *
 * @author informatica
 */
public class Address {
    String addressId;
    String country;
    String state;
    String city;
    String zone;
    String house;
    String street;
    String avenue;

    public Address(String addressId, String country, String state, String city, String zone, String house, String street) {
        this.addressId = addressId;
        this.country = country;
        this.state = state;
        this.city = city;
        this.zone = zone;
        this.house = house;
        this.street = street;
        this.avenue = avenue;
    }

    public String getAddressId() {
        return addressId;
    }

    public void setAddressId(String addressId) {
        this.addressId = addressId;
    }

    public String getCountry() {
        return country;
    }

    public void setCountry(String country) {
        this.country = country;
    }

    public String getState() {
        return state;
    }

    public void setState(String state) {
        this.state = state;
    }

    public String getCity() {
        return city;
    }

    public void setCity(String city) {
        this.city = city;
    }

    public String getZone() {
        return zone;
    }

    public void setZone(String zone) {
        this.zone = zone;
    }

    public String getHouse() {
        return house;
    }

    public void setHouse(String house) {
        this.house = house;
    }

    public String getStreet() {
        return street;
    }

    public void setStreet(String street) {
        this.street = street;
    }

    public String getAvenue() {
        return avenue;
    }

    public void setAvenue(String avenue) {
        this.avenue = avenue;
    }
    
}

    